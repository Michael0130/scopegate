// Zero-dependency PDF writer for the dispute defense letter (Master Spec §5 P1-3
// fallback: "one-click, schema-conformant JSON payload + downloadable standard
// defense letter PDF"). Produces a valid PDF 1.4 with Helvetica text only —
// deliberately no PDF library to keep the dependency surface minimal.

const PAGE = { width: 612, height: 792 };
const MARGIN_X = 54;
const TOP_Y = 742;
const LEADING = 15;
const LINES_PER_PAGE = 46;
const WRAP = 96; // Helvetica ~0.5 em average → fits the 504pt text column

function ascii(s) {
  return String(s ?? '').replace(/[^\x20-\x7e]/g, '?');
}

function esc(s) {
  return ascii(s).replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
}

function wrap(text, width = WRAP) {
  const words = ascii(text).split(/\s+/);
  const out = [];
  let line = '';
  for (const w of words) {
    if ((line + (line ? ' ' : '') + w).length > width) {
      if (line) out.push(line);
      line = w.slice(0, width);
    } else {
      line += (line ? ' ' : '') + w;
    }
  }
  if (line) out.push(line);
  return out.length ? out : [''];
}

function layoutLetter(dossier) {
  const c = dossier.contract_snapshot;
  const a = dossier.proof_of_delivery.recipient_access_log;
  const lines = [];
  const push = (text, style = 'body') => lines.push({ text, style });
  const para = (text, style = 'body') => wrap(text).forEach((l) => push(l, style));

  push('DISPUTE DEFENSE LETTER', 'title');
  push('PayPal Seller Protection Policy - Section 11 (Intangible Goods & Services)', 'subtitle');
  push('');
  push(`Dossier ID:        ${dossier.dossier_id}`);
  push(`PayPal Order ID:   ${dossier.paypal_order_id}`);
  push(`Generated at:      ${dossier.generated_at}`);
  push('Contract anchor (SHA-256, custom_id):');
  para(dossier.paypal_custom_id_anchor, 'mono');
  push('');
  push('1. AGREED CONTRACT SCOPE (pre-payment, machine-frozen)', 'h');
  para(`Quoted price: ${c.quoted_price} ${c.currency ?? 'USD'}`);
  push('Agreed deliverables:', 'b');
  c.agreed_deliverables.forEach((d) => para(`- ${d}`));
  if (c.explicit_exclusions?.length) {
    push('Explicit exclusions:', 'b');
    c.explicit_exclusions.forEach((d) => para(`- ${d}`));
  }
  para(`Maximum revisions: ${c.max_revisions}`);
  push('');
  push('2. PROOF OF DIGITAL DELIVERY (server-side access log)', 'h');
  para(`Verified payer email: ${dossier.proof_of_delivery.verified_payer_email}`);
  para(`Delivery dispatched at: ${dossier.proof_of_delivery.delivery_dispatched_at}`);
  push('Recipient pickup log:', 'b');
  para(`- Accessed at: ${a.accessed_at}`);
  para(`- Client IP: ${a.client_ip}`);
  para(`- User agent: ${a.user_agent}`);
  para(`- Artifact SHA-256: ${a.artifact_sha256}`, 'mono');
  push('');
  push('3. CRYPTOGRAPHIC ANCHOR STATEMENT', 'h');
  para(
    'Before payment, the negotiated scope above was canonicalized and hashed with SHA-256. ' +
    'The 64-character hash was written to purchase_units[0].custom_id of the PayPal order ' +
    '(limit 127 chars, 64 used), where neither party can alter it after the fact. The hash ' +
    'therefore proves that the deliverables listed in section 1 are exactly what the buyer ' +
    'agreed to and paid for.',
  );
  push('');
  push('4. FULFILLMENT CLAIM', 'h');
  para(
    'The merchant dispatched the digital artifact to the payer-verified email address on ' +
    'file and the recipient downloaded it from the logged endpoint. The artifact byte stream ' +
    'is anchored by the SHA-256 value in section 2. This letter accompanies the ' +
    'PROOF_OF_FULFILLMENT evidence payload submitted through the PayPal Disputes API, with ' +
    'the contract hash supplied as the intangible-service tracking reference.',
  );
  push('');
  push('');
  push('Generated by ScopeGate - scopegate.onrender.com', 'footer');
  return lines;
}

function contentStream(pageLines) {
  const parts = [];
  let y = TOP_Y;
  for (const { text, style } of pageLines) {
    if (text === '') {
      y -= LEADING / 2;
      continue;
    }
    const font = style === 'title' || style === 'h' || style === 'subtitle' || style === 'b' ? '/F2' : '/F1';
    const size = style === 'title' ? 16 : style === 'subtitle' ? 10 : style === 'h' ? 12 : style === 'mono' ? 9 : 10;
    parts.push(`BT ${font} ${size} Tf ${MARGIN_X} ${y} Td (${esc(text)}) Tj ET`);
    y -= style === 'title' ? LEADING + 4 : LEADING;
  }
  return parts.join('\n');
}

export function buildDefenseLetterPdf(dossier) {
  const lines = layoutLetter(dossier);
  const pages = [];
  for (let i = 0; i < lines.length; i += LINES_PER_PAGE) pages.push(lines.slice(i, i + LINES_PER_PAGE));

  // Object numbering: 1 catalog, 2 pages, 3 F1 (Helvetica), 4 F2 (Helvetica-Bold),
  // then per page: page object + content stream object.
  const objects = new Map(); // id -> body string (without "N 0 obj ... endobj")
  objects.set(1, '<< /Type /Catalog /Pages 2 0 R >>');
  const pageIds = pages.map((_, i) => 5 + i * 2);
  objects.set(2, `<< /Type /Pages /Kids [${pageIds.map((id) => `${id} 0 R`).join(' ')}] /Count ${pages.length} >>`);
  objects.set(3, '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
  objects.set(4, '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>');
  pages.forEach((pageLines, i) => {
    const pageId = pageIds[i];
    const contentId = pageId + 1;
    const stream = contentStream(pageLines);
    objects.set(pageId, `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE.width} ${PAGE.height}] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ${contentId} 0 R >>`);
    objects.set(contentId, `<< /Length ${Buffer.byteLength(stream, 'latin1')} >>\nstream\n${stream}\nendstream`);
  });

  const count = objects.size + 1; // +1 for the free object 0
  let out = '%PDF-1.4\n';
  const offsets = [0];
  for (let id = 1; id < count; id++) {
    offsets[id] = Buffer.byteLength(out, 'latin1');
    out += `${id} 0 obj\n${objects.get(id)}\nendobj\n`;
  }
  const xrefOffset = Buffer.byteLength(out, 'latin1');
  out += `xref\n0 ${count}\n0000000000 65535 f \n`;
  for (let id = 1; id < count; id++) {
    out += `${String(offsets[id]).padStart(10, '0')} 00000 n \n`;
  }
  out += `trailer\n<< /Size ${count} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;
  return Buffer.from(out, 'latin1');
}
